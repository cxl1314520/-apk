    fun getRandom(): KnowledgeItem = items.random()

    fun getRandomByCategory(category: String): KnowledgeItem =
        items.filter { it.category == category }.randomOrNull() ?: getRandom()

    fun getById(id: Int): KnowledgeItem? = items.find { it.id == id }

    fun getScheduledItem(hour: Int): KnowledgeItem {
        val categoryIndex = when (hour) {
            8  -> 0  // 常识判断
            10 -> 1  // 言语理解
            12 -> 2  // 判断推理
            14 -> 3  // 数量关系
            16 -> 4  // 资料分析
            18 -> 5  // 申论技巧
            20 -> 0  // 常识判断
            22 -> 1  // 言语理解
            else -> (0..5).random()
        }
        val categories = listOf("常识判断", "言语理解", "判断推理", "数量关系", "资料分析", "申论技巧")
        return getRandomByCategory(categories[categoryIndex])
    }
